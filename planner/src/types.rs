//! Pivot's type system: the column types the planner understands, plus
//! conversions to and from DuckDB's [`LogicalTypeId`] and parsing of constant
//! values into arrow [`Scalar`]s.
//!
//! The supported [`Type`] set is deliberately small — it mirrors what the
//! executor ([`dispatch`]) currently knows how to build columns for. If
//! DuckDB hands us a logical type outside this set, [`type_from_logical`]
//! returns [`Error::UnsupportedLogicalType`] and short-circuits the rest of
//! plan conversion, so unsupported shapes never reach
//! [`compile`](crate::compile).
//!
//! The `Type <-> LogicalTypeId` mapping is generated by the
//! `type_conversions!` macro from a single list of pairs, so adding a new
//! type is one entry instead of two near-identical match arms.

use arrow_array::{
    ArrayRef, BooleanArray, Int8Array, Int16Array, Int32Array, Int64Array, Scalar, StringViewArray,
};
use duckdb_planner::ScalarValue;
use duckdb_planner::duckdb_bridge::duckdb_types::LogicalTypeId;
use std::sync::Arc;
use thiserror::Error;

/// A column type Pivot can plan and execute against.
///
/// Each variant maps 1-1 to an arrow array kind in the executor, and
/// bidirectionally to a [`LogicalTypeId`] in DuckDB via the
/// `type_conversions!` macro below.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Type {
    Boolean,
    Int8,
    Int16,
    Int32,
    Int64,
    Utf8,
}

#[derive(Error, Debug)]
pub enum Error {
    #[error("Unsupported logical type: {0:?}")]
    UnsupportedLogicalType(LogicalTypeId),
    #[error("Unsupported scalar type: {0:?}")]
    UnsupportedScalarType(Type),
    #[error("Invalid scalar value '{raw_value}' for logical type {logical_type:?}: {reason}")]
    InvalidScalarValue {
        logical_type: LogicalTypeId,
        raw_value: String,
        reason: String,
    },
}

/// Generates a pair of conversion functions between Pivot's [`Type`] and
/// DuckDB's [`LogicalTypeId`] from a single list of pairs, so the mapping
/// is defined once and both directions stay in sync.
///
/// - `type_from_logical`: DuckDB `LogicalTypeId` -> Pivot `Type` (fallible,
///   returns `Err` for unmapped DuckDB types).
/// - `logical_from_type`: Pivot `Type` -> DuckDB `LogicalTypeId` (infallible,
///   every Pivot type has a DuckDB counterpart).
macro_rules! type_conversions {
    ( $( ($pivot:path, $duckdb:path) ),+ $(,)? ) => {
        pub fn type_from_logical(duckdb_type: LogicalTypeId) -> Result<Type, Error> {
            match duckdb_type {
                $( $duckdb => Ok($pivot), )+
                _ => Err(Error::UnsupportedLogicalType(duckdb_type)),
            }
        }

        pub fn logical_from_type(pivot_type: &Type) -> LogicalTypeId {
            match pivot_type {
                $( $pivot => $duckdb, )+
            }
        }
    };
}

type_conversions! {
    (Type::Boolean,   LogicalTypeId::BOOLEAN),
    (Type::Int8,      LogicalTypeId::TINYINT),
    (Type::Int16,     LogicalTypeId::SMALLINT),
    (Type::Int32,     LogicalTypeId::INTEGER),
    (Type::Int64,     LogicalTypeId::BIGINT),
    (Type::Utf8,      LogicalTypeId::VARCHAR),
}

/// Parse a DuckDB [`ScalarValue`] (logical type + raw string) into an arrow
/// [`Scalar<ArrayRef>`] suitable for use as a constant in the executor.
pub fn build_scalar_value(
    ScalarValue {
        logical_type,
        raw_value,
    }: ScalarValue,
) -> Result<Scalar<ArrayRef>, Error> {
    let pivot_type = type_from_logical(logical_type.clone())?;
    let array: ArrayRef = match pivot_type {
        Type::Boolean => Arc::new(
            BooleanArray::new_scalar(parse_scalar::<bool>(&raw_value, logical_type.clone())?)
                .into_inner(),
        ),
        Type::Int8 => Arc::new(
            Int8Array::new_scalar(parse_scalar::<i8>(&raw_value, logical_type.clone())?)
                .into_inner(),
        ),
        Type::Int16 => Arc::new(
            Int16Array::new_scalar(parse_scalar::<i16>(&raw_value, logical_type.clone())?)
                .into_inner(),
        ),
        Type::Int32 => Arc::new(
            Int32Array::new_scalar(parse_scalar::<i32>(&raw_value, logical_type.clone())?)
                .into_inner(),
        ),
        Type::Int64 => Arc::new(
            Int64Array::new_scalar(parse_scalar::<i64>(&raw_value, logical_type.clone())?)
                .into_inner(),
        ),
        Type::Utf8 => Arc::new(StringViewArray::new_scalar(raw_value).into_inner()),
    };

    Ok(Scalar::new(array))
}

fn parse_scalar<T>(raw_value: &str, logical_type: LogicalTypeId) -> Result<T, Error>
where
    T: std::str::FromStr,
    T::Err: std::fmt::Display,
{
    raw_value
        .parse::<T>()
        .map_err(|err| Error::InvalidScalarValue {
            logical_type,
            raw_value: raw_value.to_string(),
            reason: err.to_string(),
        })
}
