-- Insert-throughput suite: measures the `INSERT ... VALUES` write path rather
-- than query speed. It declares the hits schema once per table, exactly as the
-- query suite maps it onto pivot's SQL types (EventTime/EventDate kept as the
-- packed integer storage type the source parquet holds):
--
--   `hits` takes the parquet under `--source` as its pre-existing data, where
--   it sits, and is only ever read, untimed, to supply the rows the statements
--   carry.
--   `hits_inserted_1k`, `hits_inserted_5k` and `hits_inserted_10k` each take
--   the statements of one batch size, and each starts empty, so no measurement
--   writes on top of another's rows or another's Delta log.
--
-- The runner substitutes `{source}` with the value of `--source`.
